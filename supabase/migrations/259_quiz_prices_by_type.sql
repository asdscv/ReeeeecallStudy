-- 259: 퀴즈 값을 유형별로 나누고 전부 내립니다. 카드 한도는 2,000자로.
--
-- ── 값 ─────────────────────────────────────────────────────────────────────
--
-- 문항 하나가 $0.10 이었습니다. 유형과 무관하게 같은 값이었고, 원가와의 거리가 이랬습니다:
--
--       주관식 생성   원가 $0.000126   값 $0.10    794배
--       객관식 생성   원가 $0.000305   값 $0.10    328배
--       서술형 생성   원가 $0.000327   값 $0.15    459배
--
-- 원가는 앱과 같은 프롬프트·모델로 실제 카드 10장(서술형 3장)을 생성해 잰 값입니다. 주관식은
-- 출력이 객관식의 3분의 1입니다 — 오답 보기 셋과 그 라벨·축을 쓰지 않으니까요. 그런데 값은
-- 같았습니다.
--
-- 새 값입니다. 유닛 단가를 $0.05 → $0.005 로 내리고, 유닛 수로 유형을 가릅니다:
--
--       주관식 생성   1유닛  $0.005    40배
--       객관식 생성   2유닛  $0.010    33배
--       서술형 생성   3유닛  $0.015    46배
--       주관식 채점   2유닛  $0.010    24배
--       서술형 채점   4유닛  $0.020    23배   (최대 길이 답안 기준 원가 $0.00088)
--
-- 다섯 값이 전부 다르고 전부 지금보다 낮으며, `price-floor.test.ts` 가 요구하는 10배에서
-- 모두 두 배 이상 위입니다.
--
-- ── 왜 유닛 수가 아니라 단가를 내렸나 ──────────────────────────────────────
--
-- `units` 는 최소 1이고 정수입니다. 단가가 $0.05 면 아무리 내려도 문항당 $0.05 아래로 못
-- 갑니다. 단가를 내려야 그 아래가 열립니다.
--
-- 그리고 체험분(`quiz_trial_units` 60)은 **유닛**으로 셉니다. 유닛 수를 올려 값을 조정했다면
-- 같은 체험분이 더 적은 문항을 사게 됩니다 — 값을 내리면서 체험을 줄이는 셈입니다. 그래서
-- 생성 쪽 유닛은 유지하거나(객관식 2, 서술형 3) 내렸습니다(주관식 2 → 1). 체험으로 만들 수
-- 있는 문항 수는 같거나 늘어납니다.
--
-- 채점은 `trial_applies = false` 라 체험과 무관하므로 유닛을 올려 마진을 확보했습니다.
--
-- 하루 무료 5문항은 **문항** 단위라(mig 239, `unit_kind='item'`) 이 변경에 영향받지 않습니다.
-- `quiz_max_units_per_call` 40 도 그대로 충분합니다: 객관식 10문항 = 20유닛.
--
-- ── 카드 한도 4,000 → 2,000자 ──────────────────────────────────────────────
--
-- 소유자 판단입니다. 프로덕션 377,099장 중 2,000자를 넘는 카드가 **2장** 있어서 NOT VALID 로
-- 겁니다 — 그 두 장은 그대로 살아 있고, 앞으로 만들거나 고치는 카드만 새 한도를 지킵니다.
-- 검증을 강제하면 남의 카드를 우리가 못 쓰게 만드는 것이고, 그건 한도가 할 일이 아닙니다.
BEGIN;

-- ── 유닛 단가 ───────────────────────────────────────────────────────────────
UPDATE public.ai_pricing_settings SET quiz_unit_price_micro = 5000, updated_at = now()
 WHERE id = 1 AND quiz_unit_price_micro = 50000;

-- ── 유형별 유닛 ─────────────────────────────────────────────────────────────
UPDATE public.ai_quiz_price_units SET units = 1, updated_at = now()
 WHERE action = 'generate_short' AND units = 2;
UPDATE public.ai_quiz_price_units SET units = 2, updated_at = now()
 WHERE action = 'grade_short' AND units = 1;
UPDATE public.ai_quiz_price_units SET units = 4, updated_at = now()
 WHERE action = 'grade_essay' AND units = 2;
-- generate_mcq(2) 와 generate_essay(3) 은 유닛 그대로입니다. 단가만으로 값이 내려갑니다.

-- ── 카드 한도 ───────────────────────────────────────────────────────────────
ALTER TABLE public.cards DROP CONSTRAINT IF EXISTS cards_field_values_chars_check;
ALTER TABLE public.cards
  ADD CONSTRAINT cards_field_values_chars_check
  CHECK (public._card_text_chars(field_values) <= 2000) NOT VALID;

COMMIT;
