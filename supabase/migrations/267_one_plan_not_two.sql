-- 소유자 결정입니다. 지금 상태를 먼저 적어 둡니다:
--
--       sub_5k_monthly        Standard   $3.99   카드 5,000
--       sub_unlimited_monthly Pro       $19.99   카드 100,000
--
--       활성 구독 0건 (만료 2건, 둘 다 plan_5k)  · Pro 는 한 번도 팔린 적 없음
--       사용자 36명 · 카드 1,000장을 넘는 계정은 **1개**(공식 콘텐츠 계정 376,095장)
--       그다음으로 많은 실사용자가 781장
--
-- 그래서 이 변경으로 끊기는 구독도, 한도를 잃는 사용자도 없습니다.
--
-- ── 왜 지우지 않고 끄는가 ──────────────────────────────────────────────────
--
-- `is_active = false` 면 `get_billing_products` 가 안 돌려주고 모든 화면에서 사라집니다.
-- 행을 지우면 결제 이력이 가리키는 상품이 없어져서, 나중에 "이 사람이 무엇을 샀는가"를
-- 되짚을 수 없습니다. 판매를 멈추는 것과 기록을 지우는 것은 다른 일입니다.
--
-- 결제 제공자 쪽 매핑(LemonSqueezy variant, RevenueCat product)은 건드리지 않습니다 —
-- 카탈로그에서 빠지면 결제가 시작될 수 없고, 남은 매핑은 옛 영수증을 읽는 데 쓰입니다.
BEGIN;

UPDATE public.billing_products
   SET is_active = false
 WHERE id = 'sub_unlimited_monthly';

COMMIT;
