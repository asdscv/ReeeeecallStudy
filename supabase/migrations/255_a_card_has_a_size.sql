-- 255: 카드 한 장의 전체 텍스트에 한도를 둡니다.
--
-- 카드는 프롬프트에 통째로 들어갑니다 — 생성 한 번에 최대 열 장이니, 카드 한 장의 크기가 곧
-- 한 요청의 입력 토큰이고 곧 우리 원가입니다. 그런데 지금까지 그 크기에 상한이 없었습니다.
-- 붙여넣기 한 번으로 50KB 짜리 카드를 만들 수 있고, 그 열 장이면 500KB 가 한 요청에 들어갑니다.
-- 값은 문항당 고정이므로 그 비용은 전부 우리 쪽입니다.
--
-- ── 왜 필드별이 아니라 카드 전체인가 ───────────────────────────────────────
--
-- 필드별 한도는 필드를 늘려 우회됩니다(500자 × 10필드). 앞면/뒷면으로 나누는 것도 답이
-- 아닙니다 — 어느 필드가 어느 면인지는 템플릿의 레이아웃이 정하고, 그 레이아웃은 편집으로
-- 바뀝니다. 같은 카드가 템플릿을 고쳤다는 이유로 한도를 넘나들면 그건 한도가 아닙니다.
--
-- 프롬프트에 들어가는 단위, 청구되는 단위, 학습자가 "카드 한 장"이라고 부르는 단위가 전부
-- `field_values` 하나입니다. 거기에 겁니다.
--
-- ── 숫자 ───────────────────────────────────────────────────────────────────
--
-- 프로덕션 카드 377,099장을 재 봤습니다:
--
--       평균     264 바이트
--       p99      542 바이트
--       최대   3,132 바이트
--       4KB 초과   0장
--
-- 8,000 은 현존 최대의 2.5배입니다. 오늘 아무도 걸리지 않고, 앞으로도 정상적인 카드는 걸리지
-- 않으며, 병적인 붙여넣기만 걸립니다. 한도는 사람을 막으려고 두는 게 아니라 바닥이 빠지는 것을
-- 막으려고 둡니다.
--
-- NOT VALID 로 걸고 검증을 따로 돌립니다 — 37만 행을 잠그지 않기 위해서이고, 위 측정대로
-- 검증은 통과합니다.
BEGIN;

ALTER TABLE public.cards
  DROP CONSTRAINT IF EXISTS cards_field_values_size_check;
ALTER TABLE public.cards
  ADD CONSTRAINT cards_field_values_size_check
  CHECK (octet_length(field_values::text) <= 8000) NOT VALID;

COMMIT;

-- 별도 트랜잭션. 검증은 기존 행을 훑지만 SHARE UPDATE EXCLUSIVE 라 읽기·쓰기를 막지 않습니다.
ALTER TABLE public.cards VALIDATE CONSTRAINT cards_field_values_size_check;
